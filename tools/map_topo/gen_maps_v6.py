#!/usr/bin/env python3
"""EasyWar 地图生成器 v6.4（树状走廊版·正交臂）
全部臂为正交（竖/横），杜绝对角相邻问题；手动归属保证每据点 <= 10。
"""
import json

def render(cells, w, h):
    rows = [['.'] * w for _ in range(h)]
    for (x, y), ch in cells.items():
        rows[y][x] = ch
    return [''.join(r) for r in rows]

def arm_v(cells, x, y1, y2, owner):
    """竖臂：列 x，行 y1..y2（含），归 owner。"""
    for y in range(min(y1, y2), max(y1, y2) + 1):
        cells.setdefault((x, y), owner)

def arm_h(cells, y, x1, x2, owner):
    """横臂：行 y，列 x1..x2（含）。"""
    for x in range(min(x1, x2), max(x1, x2) + 1):
        cells.setdefault((x, y), owner)

# ============================================================
# 1. H · 双链 (1v1, 14x13) —— 双竖链 + 横梁（原版 H 树）
# ============================================================
H = {}
arm_v(H, 2, 2, 5, 'c'); arm_v(H, 2, 7, 10, 'a')
arm_v(H, 11, 2, 5, 'm'); arm_v(H, 11, 7, 10, 'u')
arm_h(H, 6, 3, 6, 'p'); arm_h(H, 6, 7, 10, 'g')
arm_h(H, 1, 3, 4, 'c'); arm_h(H, 1, 9, 10, 'm')
arm_h(H, 11, 3, 4, 'a'); arm_h(H, 11, 9, 10, 'u')
H[(2, 1)] = 'C'; H[(11, 1)] = 'M'
H[(2, 6)] = 'P'; H[(11, 6)] = 'G'
H[(2, 11)] = 'A'; H[(11, 11)] = 'U'
h_rows = render(H, 14, 13)

# ============================================================
# 2. Y · 三叉 (1v1, 15x13) —— 中心 P + 竖臂(下) + 双横臂(左/右)，U/G 卡口
# ============================================================
Y = {}
Y[(7, 6)] = 'P'
# 下臂（C 要塞端）：列 7 行 7-12
arm_v(Y, 7, 7, 12, 'c')
Y[(7, 12)] = 'C'
# 左臂（A 端 + U 卡口）：行 6 列 1-6
arm_h(Y, 6, 1, 6, 'a')
Y[(1, 6)] = 'A'; Y[(4, 6)] = 'U'
Y[(2, 6)] = 'u'; Y[(3, 6)] = 'u'
# A 端部竖向地块（臂延长线，不成 2x2）
Y[(1, 5)] = 'a'; Y[(1, 7)] = 'a'
# 右臂（M 端 + G 卡口）：行 6 列 8-13
arm_h(Y, 6, 8, 13, 'm')
Y[(13, 6)] = 'M'; Y[(10, 6)] = 'G'
Y[(11, 6)] = 'g'; Y[(12, 6)] = 'g'
# M 端部竖向地块
Y[(13, 5)] = 'm'; Y[(13, 7)] = 'm'
y_rows = render(Y, 15, 13)

# ============================================================
# 3. 阶梯 · 双峰 (1v1, 15x11) —— 之字主走廊 + 两分叉
# ============================================================
L = {}
arm_h(L, 9, 1, 5, 'a')     # A 段
arm_v(L, 5, 6, 8, 'a')     # A 段上行
arm_v(L, 5, 3, 4, 'p')     # P 段
arm_h(L, 5, 6, 9, 'p')     # P 段
arm_h(L, 5, 10, 12, 'm')   # M 段
arm_v(L, 9, 1, 4, 'm')     # M 段
arm_h(L, 1, 10, 12, 'm')   # M 段
# 分叉1：C(1,7) 连主走廊 (5,7)
arm_h(L, 7, 1, 4, 'c')
L[(1, 7)] = 'C'
# 分叉2：G(13,3) 连主走廊 (9,3)
arm_h(L, 3, 10, 13, 'g')
L[(13, 3)] = 'G'
# 据点
L[(1, 9)] = 'A'
L[(13, 1)] = 'M'
L[(5, 5)] = 'P'
L[(9, 5)] = 'U'
l_rows = render(L, 15, 11)

# ============================================================
# 4. 三叉 · 星 (3人, 17x13) —— 中心 X + 上/左/右正交臂，臂中要塞
# ============================================================
T = {}
T[(8, 6)] = 'X'
arm_v(T, 8, 1, 5, 'a'); T[(8, 1)] = 'A'; T[(8, 3)] = 'P'
arm_h(T, 7, 4, 8, 'm'); T[(4, 7)] = 'M'; T[(6, 7)] = 'U'
arm_h(T, 6, 9, 13, 'c'); T[(13, 6)] = 'C'; T[(11, 6)] = 'G'
# 臂端平台（各 2 块）
T[(7, 1)] = 'a'; T[(9, 1)] = 'a'
T[(3, 7)] = 'm'; T[(3, 8)] = 'm'
T[(13, 5)] = 'c'; T[(13, 7)] = 'c'
t_rows = render(T, 17, 13)

# ============================================================
# 5. 十字 · 星 (4人, 17x13) —— 中心 X + 上/下/左/右正交臂，上下卡要塞
# ============================================================
CR = {}
CR[(8, 6)] = 'X'
arm_v(CR, 8, 1, 5, 'a'); CR[(8, 1)] = 'A'; CR[(8, 3)] = 'P'
arm_v(CR, 8, 7, 11, 'c'); CR[(8, 11)] = 'C'; CR[(8, 9)] = 'G'
arm_h(CR, 6, 1, 7, 'u'); CR[(1, 6)] = 'U'; CR[(4, 6)] = 'X'
arm_h(CR, 6, 9, 15, 'm'); CR[(15, 6)] = 'M'; CR[(11, 6)] = 'X'
cr_rows = render(CR, 17, 13)

# ============================================================
# 7. 双子 · 星 (6人, 17x13) —— 两个三叉星串联（T 形臂）
# ============================================================
TW = {}
TW[(4, 6)] = 'X'; TW[(13, 6)] = 'X'
# 左星 X1(4,6)：A 上、C 下、M 左
arm_v(TW, 4, 1, 5, 'a'); TW[(4, 1)] = 'A'
arm_v(TW, 4, 7, 11, 'c'); TW[(4, 11)] = 'C'
arm_h(TW, 6, 0, 3, 'm'); TW[(0, 6)] = 'M'
# 右星 X2(13,6)：U 上、P 下、G 右
arm_v(TW, 13, 1, 5, 'u'); TW[(13, 1)] = 'U'
arm_v(TW, 13, 7, 11, 'p'); TW[(13, 11)] = 'P'
arm_h(TW, 6, 14, 16, 'g'); TW[(16, 6)] = 'G'
# 连接走廊 行6 列5-12
arm_h(TW, 6, 5, 12, 'x')
sx_rows = render(TW, 17, 13)

OUT = {
    'h-chain': h_rows,
    'y-fork': y_rows,
    'ladder': l_rows,
    'tristar': t_rows,
    'crosstar': cr_rows,
    'twinstar': sx_rows,
}
print(json.dumps(OUT))
